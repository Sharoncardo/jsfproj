-- Flyway Migration V3: Consolidate Problem Catalog, Progressive Hints, and Playbook Revisions Schema

-- Topics table
CREATE TABLE topics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    slug VARCHAR(100) NOT NULL,
    description TEXT,
    display_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uk_topics_code UNIQUE (code),
    CONSTRAINT uk_topics_slug UNIQUE (slug)
);

CREATE INDEX idx_topics_code ON topics(code);
CREATE INDEX idx_topics_slug ON topics(slug);

-- Problems table
CREATE TABLE problems (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id BIGINT NOT NULL,
    topic_code VARCHAR(50) NOT NULL,
    title VARCHAR(200) NOT NULL,
    slug VARCHAR(100) NOT NULL,
    difficulty VARCHAR(20) NOT NULL,
    leetcode_number INTEGER,
    description TEXT NOT NULL,
    input_format TEXT,
    output_format TEXT,
    constraints TEXT,
    sample_input TEXT,
    sample_output TEXT,
    sample_explanation TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_problems_topic FOREIGN KEY (topic_id) REFERENCES topics(id) ON DELETE RESTRICT,
    CONSTRAINT uk_problems_slug UNIQUE (slug),
    CONSTRAINT chk_problem_difficulty CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD'))
);

CREATE INDEX idx_problems_slug ON problems(slug);
CREATE INDEX idx_problems_topic_code ON problems(topic_code);
CREATE INDEX idx_problems_difficulty ON problems(difficulty);

-- Progressive Hints table (strictly 4 progressive hint levels per problem)
CREATE TABLE hints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id BIGINT NOT NULL,
    level INTEGER NOT NULL,
    title VARCHAR(150) NOT NULL,
    content TEXT NOT NULL,
    time_complexity VARCHAR(100),
    space_complexity VARCHAR(100),
    CONSTRAINT fk_hints_problem FOREIGN KEY (problem_id) REFERENCES problems(id) ON DELETE CASCADE,
    CONSTRAINT uk_hints_problem_level UNIQUE (problem_id, level),
    CONSTRAINT chk_hint_level CHECK (level >= 1 AND level <= 4)
);

CREATE INDEX idx_hints_problem ON hints(problem_id);

-- Language Starter Templates table (strictly boilerplate skeleton stubs, no complete working solutions)
CREATE TABLE language_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id BIGINT NOT NULL,
    name VARCHAR(50) NOT NULL,
    language_key VARCHAR(20) NOT NULL,
    starter_template TEXT NOT NULL,
    CONSTRAINT fk_lang_problem FOREIGN KEY (problem_id) REFERENCES problems(id) ON DELETE CASCADE,
    CONSTRAINT uk_lang_problem_key UNIQUE (problem_id, language_key)
);

CREATE INDEX idx_lang_problem ON language_options(problem_id);

-- User Hint Progress table (persists sequential progressive unlocked hint level 0-4 for authenticated user)
CREATE TABLE user_hint_progress (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL,
    problem_id BIGINT NOT NULL,
    unlocked_level INTEGER NOT NULL DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_hint_prog_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_hint_prog_problem FOREIGN KEY (problem_id) REFERENCES problems(id) ON DELETE CASCADE,
    CONSTRAINT uk_user_hint_prog UNIQUE (user_id, problem_id),
    CONSTRAINT chk_unlocked_level CHECK (unlocked_level >= 0 AND unlocked_level <= 4)
);

CREATE INDEX idx_hint_prog_user ON user_hint_progress(user_id);
CREATE INDEX idx_hint_prog_problem ON user_hint_progress(problem_id);

-- User Problem Revisions table (Logic Playbook personal mnemonic, approach, reasoning, and complexities)
CREATE TABLE user_problem_revisions (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL,
    problem_id BIGINT NOT NULL,
    personal_mnemonic TEXT,
    personal_approach TEXT,
    reasoning TEXT,
    time_complexity VARCHAR(50),
    time_complexity_explanation TEXT,
    space_complexity VARCHAR(50),
    space_complexity_explanation TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_rev_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_rev_problem FOREIGN KEY (problem_id) REFERENCES problems(id) ON DELETE CASCADE,
    CONSTRAINT uk_user_problem_rev UNIQUE (user_id, problem_id)
);

CREATE INDEX idx_rev_user ON user_problem_revisions(user_id);
CREATE INDEX idx_rev_problem ON user_problem_revisions(problem_id);

-- Submissions table
CREATE TABLE submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id BIGINT NOT NULL,
    user_id UUID,
    language VARCHAR(20) NOT NULL,
    source_code TEXT NOT NULL,
    status VARCHAR(50) NOT NULL,
    execution_time_ms INTEGER,
    memory_kb INTEGER,
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    feedback TEXT,
    session_id VARCHAR(100),
    CONSTRAINT fk_submissions_problem FOREIGN KEY (problem_id) REFERENCES problems(id) ON DELETE CASCADE,
    CONSTRAINT fk_submissions_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_submissions_problem ON submissions(problem_id);
CREATE INDEX idx_submissions_user ON submissions(user_id);
